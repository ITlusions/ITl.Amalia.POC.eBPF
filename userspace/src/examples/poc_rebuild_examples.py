    print("\n[4] Exporting POC...")
    poc_path = builder.export_poc("/tmp/exploit_custom.py")
    print(f"    Exported to: {poc_path}")
    
    # Step 5: Test reliability
    print("\n[5] Testing reliability (10 iterations)...")
    results = builder.test_poc(poc_path, iterations=10)
    print(f"    Success rate: {results['success_rate']*100:.1f}%")
    print(f"    Reliable: {results['reliable']}")


