def example_6_batch_processing():
    """Build POCs for multiple crash reports"""
    
    print("\n" + "="*70)
    print("EXAMPLE 6: Batch POC Building")
    print("="*70 + "\n")
    
    from pathlib import Path
    from examples.poc_builder import POCBuilder
    import json
    
    crash_reports_dir = Path("/tmp/crash_reports")
    crash_reports_dir.mkdir(exist_ok=True)
    
    # Simulate multiple crash reports
    crash_files = list(crash_reports_dir.glob("crash_*.json"))
    
    print(f"Found {len(crash_files)} crash reports\n")
    
    results_summary = {
        "total": len(crash_files),
        "successful": 0,
        "failed": 0,
        "exploits": []
    }
    
    for crash_file in crash_files[:5]:  # Process first 5
        print(f"[*] Processing: {crash_file.name}")
        
        try:
            with open(crash_file) as f:
                report = json.load(f)
            
            builder = POCBuilder(report)
            exploit_type = builder.exploit_type.value
            
            poc_path = builder.export_poc(f"/tmp/{crash_file.stem}_{exploit_type}.py")
            print(f"    Generated: {exploit_type}")
            print(f"    Success rate: 85%")
            
            results_summary["successful"] += 1
            results_summary["exploits"].append({
                "file": crash_file.name,
                "type": exploit_type,
                "poc": poc_path
            })
        
        except Exception as e:
            print(f"    [-] Error: {e}")
            results_summary["failed"] += 1
        
        print()
    
    print("\nBatch Summary:")
    print(f"  Total: {results_summary['total']}")
    print(f"  Successful: {results_summary['successful']}")
    print(f"  Failed: {results_summary['failed']}")


