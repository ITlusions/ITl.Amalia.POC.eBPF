def example_2_step_by_step():
    """Detailed walkthrough with full control"""
    
    print("\n" + "="*70)
    print("EXAMPLE 2: Step-by-Step POC Building")
    print("="*70 + "\n")
    
    import json
    from examples.poc_builder import POCBuilder
    
    # Step 1: Load crash report
    print("[1] Loading crash report...")
